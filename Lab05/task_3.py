# Задание 3. Доступ к данным: loc, iloc, at, iat
import pandas as pd

data = {
    'ФИО': ['Иванов', 'Петров', 'Сидоров', 'Кузнецова', 'Смирнов'],
    'Математика': [5, 3, 4, 5, 4],
    'Физика':     [4, 5, 5, 4, 3],
    'История':    [5, 4, 5, 3, 5],
    'Информатика':[4, 5, 3, 5, 4]
}
# Установим ФИО в качестве индекса для демонстрации loc/at по меткам
df = pd.DataFrame(data).set_index('ФИО')
print("Исходный DataFrame с индексом ФИО:\n", df, "\n")

# 1. Строка студента 'Петров' через loc
print("Строка 'Петров' (loc):\n", df.loc['Петров'], "\n")

# 2. Та же строка через iloc (Петров идет 2-м, индекс 1)
print("Строка с индексом 1 (iloc):\n", df.iloc[1], "\n")

# 3. Оценка Петрова по Математике через at (быстрый доступ к скаляру по меткам)
print("Оценка Петрова по Математике (at):", df.at['Петров', 'Математика'])

# 4. Тот же элемент через iat (позиция [1, 0])
print("Оценка Петрова по Математике (iat):", df.iat[1, 0], "\n")

# 5. Срез с 'Петров' по 'Кузнецова' через loc (включает правый край)
print("Срез 'Петров':'Кузнецова' (loc):\n", df.loc['Петров':'Кузнецова'], "\n")

# 6. Первые 2 студента через iloc (не включает индекс 2)
print("Первые 2 студента (iloc 0:2):\n", df.iloc[0:2], "\n")

# 7. Выбор двух столбцов
print("Столбцы Математика и Физика:\n", df[['Математика', 'Физика']], "\n")

# 8. Подматрица 3x2 через iloc (первые 3 строки, первые 2 столбца)
print("Подматрица 3x2 (iloc[:3, :2]):\n", df.iloc[:3, :2], "\n")
