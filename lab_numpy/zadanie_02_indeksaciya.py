"""Задание 2. Индексация и срезы."""

import numpy as np

np.random.seed(42)

print("=" * 50)
print("ОДНОМЕРНЫЙ МАССИВ")
print("=" * 50)

# Одномерный массив из 20 случайных чисел от 1 до 100
arr = np.random.randint(1, 101, size=20)
print("Массив:", arr)

print("\nПервые 5 элементов  :", arr[:5])
print("Последние 5 элементов:", arr[-5:])
print("Каждый второй        :", arr[::2])
print("В обратном порядке   :", arr[::-1])

print("\n" + "=" * 50)
print("МАТРИЦА 4×5")
print("=" * 50)

# Матрица 4×5 из случайных чисел от 1 до 100
mat = np.random.randint(1, 101, size=(4, 5))
print("Матрица:\n", mat)

print("\nПервая строка         :", mat[0])
print("Последний столбец     :", mat[:, -1])

# Подматрица 2×3 из центра: строки 1-2, столбцы 1-3
sub = mat[1:3, 1:4]
print("Подматрица 2×3 (центр):\n", sub)

# Изменение элемента [0, 0] на 999
print("\nЭлемент [0, 0] до изменения:", mat[0, 0])
mat[0, 0] = 999
print("Элемент [0, 0] после изменения:", mat[0, 0])
print("Матрица после изменения:\n", mat)
